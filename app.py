    "import streamlit as st\n",
    "import pandas as pd\n",
    "from sklearn.model_selection import train_test_split\n",
    "from sklearn.neighbors import KNeighborsClassifier\n",
    "from sklearn.metrics import accuracy_score\n",
    "import joblib\n",
    "\n",
    "# Sayfa başlığı\n",
    "st.title(\"🐧 Penguen Türü Tahmin Arayüzü\")\n",
    "st.write(\"Görseldeki koda birebir uygun olarak hazırlanan arayüz.\")\n",
    "\n",
    "# Modelin eğitilmesi veya önbellekten yüklenmesi\n",
    "@st.cache_resource\n",
    "def model_hazirla():\n",
    "    veri = pd.read_csv(\"penguins.csv\")\n",
    "    \n",
    "    X = veri.drop(\"species\", axis=1)\n",
    "    y = veri[\"species\"]\n",
    "\n",
    "    X_encoded = pd.get_dummies(X, columns=[\"island\", \"sex\"], drop_first=True)\n",
    "\n",
    "    X_eg, X_test, y_eg, y_test = train_test_split(X_encoded, y, test_size=0.2, random_state=42, stratify=y)\n",
    "\n",
    "    model = KNeighborsClassifier(n_neighbors=10)\n",
    "    model.fit(X_eg, y_eg)\n",
    "\n",
    "    tahmin = model.predict(X_test)\n",
    "    dogruluk = accuracy_score(y_test, tahmin)\n",
    "    \n",
    "    return model, X_encoded.columns, dogruluk\n",
    "\n",
    "model, model_columns, dogruluk = model_hazirla()\n",
    "\n",
    "st.sidebar.success(f\"Model Eğitildi! Doğruluk: {dogruluk:.4f}\")\n",
    "\n",
    "# Kullanıcıdan girdi alma (Görseldeki değerler varsayılan olarak ayarlandı)\n",
    "st.sidebar.header(\"Yeni Penguen Verisi\")\n",
    "\n",
    "island = st.sidebar.selectbox(\"island\", [\"Torgersen\", \"Biscoe\", \"Dream\"])\n",
    "bill_length_mm = st.sidebar.number_input(\"bill_length_mm\", value=46.0)\n",
    "bill_depth_mm = st.sidebar.number_input(\"bill_depth_mm\", value=18.9)\n",
    "flipper_length_mm = st.sidebar.number_input(\"flipper_length_mm\", value=181.0)\n",
    "body_mass_g = st.sidebar.number_input(\"body_mass_g\", value=3750.0)\n",
    "sex = st.sidebar.selectbox(\"sex\", [\"FEMALE\", \"MALE\"])\n",
    "\n",
    "# Görseldeki kodun birebir arayüze uyarlanmış hali\n",
    "if st.button(\"Tahmin Et\"):\n",
    "    yeni = pd.DataFrame({\n",
    "        \"island\": [island],\n",
